#!/usr/bin/env node
// Writes bingeon-web/.env.<environment> from the deployed stacks' outputs, so
// the web app (local `pnpm web:dev` or a CI build) talks to that
// environment's Cognito, api function and catalogue. See aws.mjs for where
// the environment and credentials come from.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { aws, environment, projectName, region, root } from "./aws.mjs";

function stackOutputs(stack) {
  const stackName = `${projectName}-${environment}-${stack}`;
  const json = aws([
    "cloudformation",
    "describe-stacks",
    "--stack-name",
    stackName,
    "--query",
    "Stacks[0].Outputs",
    "--output",
    "json",
  ]);

  const outputs = Object.fromEntries((JSON.parse(json) ?? []).map((o) => [o.OutputKey, o.OutputValue]));

  return (key) => {
    // A stack still being created has no outputs yet; fail rather than build
    // a bundle with empty configuration.
    if (!outputs[key]) {
      console.error(`Stack ${stackName} has no output named ${key}.`);
      process.exit(1);
    }
    return outputs[key];
  };
}

const web = stackOutputs("web");
const auth = stackOutputs("auth");
const api = stackOutputs("api");

const values = {
  VITE_AWS_REGION: region,
  VITE_API_FUNCTION_NAME: api("ApiFunctionName"),
  VITE_AMPLIFY_USER_POOL_ID: auth("UserPoolId"),
  VITE_AMPLIFY_USER_POOL_CLIENT_ID: auth("UserPoolClientId"),
  VITE_AMPLIFY_IDENTITY_POOL_ID: auth("IdentityPoolId"),
  VITE_AMPLIFY_OAUTH_DOMAIN: `${auth("OAuthDomain")}.auth.${region}.amazoncognito.com`,
  // Not in the bundle (no VITE_ prefix): `vite dev` sends /catalog here.
  SITE_URL: web("SiteUrl"),
};

const target = join(root, "bingeon-web", `.env.${environment}`);
const lines = Object.entries(values).map(([key, value]) => `${key}=${value}`);
writeFileSync(
  target,
  [`# Generated by scripts/web-env.mjs from ${projectName}-${environment}-* outputs.`, ...lines, ""].join("\n"),
);

console.log(`Wrote ${target}`);
